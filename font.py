CHAR_W = 5
CHAR_H = 7


def text_width(text, scale, spacing=1):
    """Pixel width of text at the given scale (spacing in font pixels)."""
    if not text:
        return 0
    adv = (CHAR_W + spacing) * scale
    return len(text) * adv - spacing * scale


def draw_text(canvas, x, y, text, scale, colour, spacing=1):
    """Draw text with its top-left corner at (x, y). Unknown chars are skipped."""
    cx = x
    for ch in text:
        glyph = FONT.get(ch)
        if glyph is not None:
            for row in range(CHAR_H):
                bits = glyph[row]
                for col in range(CHAR_W):
                    if bits[col] == "1":
                        canvas.fill_rect(
                            cx + col * scale, y + row * scale,
                            cx + (col + 1) * scale, y + (row + 1) * scale,
                            colour,
                        )
        cx += (CHAR_W + spacing) * scale


def draw_text_centred(canvas, cx, y, text, scale, colour, spacing=1):
    """Draw text centred horizontally on cx, top edge at y."""
    w = text_width(text, scale, spacing)
    draw_text(canvas, cx - w // 2, y, text, scale, colour, spacing)


def draw_text_shadow(canvas, x, y, text, scale, colour, dx, dy, spacing=1):
    draw_text(canvas, x + dx, y + dy, text, scale, colour, spacing)
